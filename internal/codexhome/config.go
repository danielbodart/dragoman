// Package codexhome is Dragoman's isolated CODEX_HOME: the user's codex
// config verbatim plus a managed block of permission profiles, the
// execpolicy rules compiled from Claude's Bash rules, and the user's auth and
// caches linked in.
//
// Per-host network filtering is only enforceable through Codex's network
// proxy plus a permission profile that lives in config.toml (verified against
// codex-cli 0.150.1: the app-server `config` map does dotted scalar overrides
// and can't build a [permissions] table, and Codex reads the selected profile
// once at thread/start). So Dragoman keeps one delimited block it overwrites,
// never appends, so it can never accumulate.
//
// This file is the pure string half; home.go is the IO.
package codexhome

import (
	"encoding/json"
	"fmt"
	"regexp"
	"strings"
)

// The delimiters of Dragoman's region. Everything between them is ours.
const (
	beginMarker = "# >>> DRAGOMAN MANAGED (do not edit — regenerated by Dragoman) >>>"
	endMarker   = "# <<< DRAGOMAN MANAGED <<<"
)

// Entry is one ordered key = value rule: a host and its allow/deny, or a path
// and its access.
type Entry struct {
	Key   string
	Value string
}

// Network is a profile's network axis: the coarse switch, plus per-host
// rules. Domain rules need the proxy to enforce; deny wins in Codex.
type Network struct {
	Enabled bool
	Domains []Entry
}

// Filesystem is a profile's filesystem axis, mirroring Claude's
// sandbox.filesystem lists. Absolute paths go in the top-level
// [...filesystem] table; relative paths and globs under the
// :workspace_roots token, portable across the isolated CODEX_HOME.
type Filesystem struct {
	Paths            []Entry
	WorkspaceRoots   []Entry
	GlobScanMaxDepth *int
}

// Profile is one Codex permission profile Dragoman manages: a built-in base
// scope (:read-only, :workspace) plus network and filesystem rules, selected
// per thread by thread/start's `permissions`.
type Profile struct {
	ID         string
	Base       string
	Network    *Network
	Filesystem *Filesystem
}

// RenderManagedBlock renders the network-proxy toggle (only when some profile
// carries domain rules: no domains, no proxy) and one [permissions.<id>]
// profile per entry.
//
// The block is all [table] sections, no bare root keys, so it is safe to
// append after arbitrary user content. default_permissions, the one root key
// Codex needs once a profile exists, is prepended by the caller.
func RenderManagedBlock(profiles []Profile) string {
	if len(profiles) == 0 {
		return ""
	}
	lines := []string{beginMarker}
	for _, p := range profiles {
		if p.Network != nil && len(p.Network.Domains) > 0 {
			lines = append(lines, "[features.network_proxy]", "enabled = true", "")
			break
		}
	}
	for i, p := range profiles {
		if i > 0 {
			lines = append(lines, "")
		}
		lines = append(lines, fmt.Sprintf("[permissions.%s]", p.ID), "extends = "+tomlString(p.Base))
		if p.Network != nil {
			lines = append(lines, fmt.Sprintf("[permissions.%s.network]", p.ID), fmt.Sprintf("enabled = %t", p.Network.Enabled))
			if len(p.Network.Domains) > 0 {
				lines = append(lines, fmt.Sprintf("[permissions.%s.network.domains]", p.ID))
				for _, d := range p.Network.Domains {
					lines = append(lines, tomlString(d.Key)+" = "+tomlString(d.Value))
				}
			}
		}
		if fs := p.Filesystem; fs != nil && (len(fs.Paths) > 0 || len(fs.WorkspaceRoots) > 0) {
			lines = append(lines, fmt.Sprintf("[permissions.%s.filesystem]", p.ID))
			if fs.GlobScanMaxDepth != nil {
				lines = append(lines, fmt.Sprintf("glob_scan_max_depth = %d", *fs.GlobScanMaxDepth))
			}
			for _, e := range fs.Paths {
				lines = append(lines, tomlString(e.Key)+" = "+tomlString(e.Value))
			}
			if len(fs.WorkspaceRoots) > 0 {
				lines = append(lines, fmt.Sprintf(`[permissions.%s.filesystem.":workspace_roots"]`, p.ID))
				for _, e := range fs.WorkspaceRoots {
					lines = append(lines, tomlString(e.Key)+" = "+tomlString(e.Value))
				}
			}
		}
	}
	lines = append(lines, endMarker)
	return strings.Join(lines, "\n")
}

// RenderRules renders Claude's allow/deny Bash rules as a Codex execpolicy
// .rules file, the config-layer enforcement that binds for every command,
// independent of the approval round-trip: deny prefixes become
// decision="forbidden" (blocked in every mode, and the strictest match wins,
// so deny beats allow), allow prefixes decision="allow". No rules, "".
func RenderRules(allow, deny [][]string) string {
	var lines []string
	for _, p := range deny {
		lines = append(lines, prefixRule(p, "forbidden", "Claude deny rule"))
	}
	for _, p := range allow {
		lines = append(lines, prefixRule(p, "allow", ""))
	}
	if len(lines) == 0 {
		return ""
	}
	return strings.Join(lines, "\n") + "\n"
}

// prefixRule is one prefix_rule(...) line, its tokens JSON-encoded (Starlark
// string literals).
func prefixRule(prefix []string, decision, justification string) string {
	tokens := make([]string, len(prefix))
	for i, t := range prefix {
		tokens[i] = jsonString(t)
	}
	reason := ""
	if justification != "" {
		reason = ", justification=" + jsonString(justification)
	}
	return fmt.Sprintf("prefix_rule(pattern=[%s], decision=%s%s)", strings.Join(tokens, ", "), jsonString(decision), reason)
}

// SpliceManagedBlock replaces any prior managed block in existing with block,
// keeping everything else verbatim; with no prior block, block is appended
// after a blank line.
func SpliceManagedBlock(existing, block string) string {
	stripped := StripManagedBlock(existing)
	if strings.TrimSpace(block) == "" {
		return stripped
	}
	if strings.TrimSpace(stripped) == "" {
		return block + "\n"
	}
	return strings.TrimRight(stripped, "\n") + "\n\n" + block + "\n"
}

// StripManagedBlock removes the managed block and the blank lines hugging
// it. A missing or half-written block leaves the text alone.
func StripManagedBlock(existing string) string {
	begin := strings.Index(existing, beginMarker)
	if begin == -1 {
		return existing
	}
	end := strings.Index(existing[begin:], endMarker)
	if end == -1 {
		return existing
	}
	after := begin + end + len(endMarker)
	before := strings.TrimRight(existing[:begin], "\n")
	rest := strings.TrimLeft(existing[after:], "\n")
	switch {
	case before == "":
		return rest
	case rest == "":
		return before + "\n"
	}
	return before + "\n\n" + rest
}

var defaultPermissions = regexp.MustCompile(`(?m)^\s*default_permissions\s*=`)

// HasDefaultPermissions says whether config sets a root default_permissions
// outside the managed block.
func HasDefaultPermissions(config string) bool {
	return defaultPermissions.MatchString(StripManagedBlock(config))
}

// WithDefaultPermissions prepends default_permissions = value when config has
// none: a bare root key must lead the file, before any [table]. A value the
// user set is kept.
func WithDefaultPermissions(config, value string) string {
	if HasDefaultPermissions(config) {
		return config
	}
	return "default_permissions = " + tomlString(value) + "\n" + config
}

// tomlString is a double-quoted TOML basic string.
func tomlString(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return `"` + s + `"`
}

// jsonString is JSON.stringify of a string, as the TypeScript wrote rules.
func jsonString(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}
