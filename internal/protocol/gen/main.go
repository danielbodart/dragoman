// Command gen writes internal/protocol/protocol_gen.go: Go types for the parts
// of Codex's app-server protocol Dragoman uses, from the JSON Schema that
// `mise run regen-protocol` writes from the installed codex.
//
//	go run ./internal/protocol/gen          rewrite the file
//	go run ./internal/protocol/gen -check   fail if the file is out of date
//
// Only the roots below and the types they reach are written. The protocol is
// Codex's, so the types are lenient by construction:
//
//   - a field that is optional or nullable is a pointer (or a nil slice or
//     map), so a missing one decodes to nil rather than failing;
//   - an enum is an open string type with known constants, never a closed
//     set, so a value Codex adds next release still decodes;
//   - a union (oneOf) keeps the JSON it was decoded from in Raw, and its
//     discriminator, so a variant Codex adds next release decodes as an
//     unknown one with its type name rather than as an error;
//   - a shape the generator cannot model becomes json.RawMessage.
//
// The generator itself is ours, so it is strict: a name it cannot make
// unique, or a root it cannot find, fails the run.
package main

