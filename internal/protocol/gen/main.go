type schema = map[string]any

func main() {
	in := flag.String("schema", "generated/codex-protocol/schema/codex_app_server_protocol.schemas.json", "the JSON Schema bundle")
	out := flag.String("out", "internal/protocol/protocol_gen.go", "the Go file to write")
	check := flag.Bool("check", false, "fail if -out differs from what would be written, rather than writing it")
	flag.Parse()

	source, err := generate(*in)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	if *check {
		current, _ := os.ReadFile(*out)
		if !bytes.Equal(current, source) {
			fmt.Fprintf(os.Stderr, "gen: %s is out of date with %s: run `go run ./internal/protocol/gen`\n", *out, *in)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*out, source, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func generate(path string) ([]byte, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var bundle schema
	if err := json.Unmarshal(raw, &bundle); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	g := &generator{bundle: bundle, names: map[string]string{}, owners: map[string]string{}, decls: map[string]string{}}
	for _, ref := range roots {
		if _, err := g.named(ref); err != nil {
			return nil, err
		}
	}
	for len(g.queue) > 0 {
		ref := g.queue[0]
		g.queue = g.queue[1:]
		if err := g.declare(ref); err != nil {
			return nil, err
		}
	}
	if g.err != nil {
		return nil, g.err
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/protocol/gen from generated/codex-protocol/schema; DO NOT EDIT.\n\n")
	b.WriteString("package protocol\n\nimport \"encoding/json\"\n\n")
	b.WriteString("var _ json.RawMessage\n\n")
	names := make([]string, 0, len(g.decls))
	for name := range g.decls {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		b.WriteString(g.decls[name])
		b.WriteString("\n")
	}
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated code does not parse: %w", err)
	}
	return formatted, nil
}

type generator struct {
	bundle schema
	// names maps a $ref to its Go type name; owners maps a Go type name back
	// to whoever claimed it, so two schemas can never share a name.
	names  map[string]string
	owners map[string]string
	decls  map[string]string
	queue  []string
	err    error
}

func (g *generator) fail(format string, args ...any) {
	if g.err == nil {
		g.err = fmt.Errorf(format, args...)
	}
}

func (g *generator) resolve(ref string) (schema, error) {
	if !strings.HasPrefix(ref, "#/") {
		return nil, fmt.Errorf("unsupported $ref %q", ref)
	}
	var node any = g.bundle
	for _, part := range strings.Split(ref[2:], "/") {
		m, ok := node.(schema)
		if !ok {
			return nil, fmt.Errorf("$ref %q: %q is not an object", ref, part)
		}
		if node, ok = m[part]; !ok {
			return nil, fmt.Errorf("$ref %q: no %q", ref, part)
		}
	}
	s, ok := node.(schema)
	if !ok {
		return nil, fmt.Errorf("$ref %q is not a schema", ref)
	}
	return s, nil
}

// named returns the Go name of a $ref, queueing its declaration the first
// time. A v1 definition whose name a v2 one also uses is prefixed V1.
func (g *generator) named(ref string) (string, error) {
	if name, ok := g.names[ref]; ok {
		return name, nil
	}
	if _, err := g.resolve(ref); err != nil {
		return "", err
	}
	base := ref[strings.LastIndex(ref, "/")+1:]
	name := ident(base)
	if !strings.Contains(ref, "/v2/") {
		if _, err := g.resolve("#/definitions/v2/" + base); err == nil {
			v1, _ := g.resolve(ref)
			v2, _ := g.resolve("#/definitions/v2/" + base)
			if !equalJSON(v1, v2) {
				name = "V1" + name
			} else {
				// The same schema under both: share the v2 one.
				return g.named("#/definitions/v2/" + base)
			}
		}
	}
	if err := g.claim(name, ref); err != nil {
		return "", err
	}
	g.names[ref] = name
	g.queue = append(g.queue, ref)
	return name, nil
}

func (g *generator) claim(name, owner string) error {
	if other, ok := g.owners[name]; ok && other != owner {
		return fmt.Errorf("Go name %s is wanted by both %s and %s", name, other, owner)
	}
	g.owners[name] = owner
	return nil
}

func (g *generator) declare(ref string) error {
	s, err := g.resolve(ref)
	if err != nil {
		return err
	}
	name := g.names[ref]
	g.declareNamed(name, s)
	return nil
}

// declareNamed writes the declaration of a named type for s: a struct, a
// union, an enum or, failing those, a defined type over whatever s is.
func (g *generator) declareNamed(name string, s schema) {
	if _, done := g.decls[name]; done {
		return
	}
	g.decls[name] = "" // reserve, so a recursive reference does not redeclare
	doc := comment(str(s["description"]))
	switch {
	case isUnion(s):
		g.decls[name] = doc + g.union(name, s)
	case isStringEnum(s):
		g.decls[name] = doc + enumDecl(name, enumValues(s))
	case isStruct(s):
		g.decls[name] = doc + g.structDecl(name, s)
	default:
		typ, _ := g.typeOf(s, name)
		if typ == name {
			typ = "json.RawMessage"
		}
		g.decls[name] = doc + fmt.Sprintf("type %s = %s\n", name, typ)
	}
}

// typeOf is the Go type for s, and whether s admits null. Inline structs and
// unions are declared under hint.
func (g *generator) typeOf(s schema, hint string) (string, bool) {
	if ref, ok := s["$ref"].(string); ok {
		name, err := g.named(ref)
		if err != nil {
			g.fail("%v", err)
			return "json.RawMessage", false
		}
		return name, false
	}
	if all, ok := s["allOf"].([]any); ok && len(all) == 1 {
		if inner, ok := all[0].(schema); ok {
			return g.typeOf(inner, hint)
		}
	}
	if anyOf, ok := s["anyOf"].([]any); ok {
		rest, nullable := withoutNull(anyOf)
		if len(rest) == 1 {
			typ, innerNull := g.typeOf(rest[0], hint)
			return typ, nullable || innerNull
		}
		name := g.inlineName(s, hint)
		copied := schema{"oneOf": toAny(rest)}
		g.declareNamed(name, copied)
		return name, nullable
	}
	if isUnion(s) {
		name := g.inlineName(s, hint)
		g.declareNamed(name, s)
		return name, false
	}
	types, nullable := typesOf(s)
	if len(types) != 1 {
		return "json.RawMessage", nullable
	}
	switch types[0] {
	case "string":
		return "string", nullable
	case "integer":
		return "int64", nullable
	case "number":
		return "float64", nullable
	case "boolean":
		return "bool", nullable
	case "array":
		items, _ := s["items"].(schema)
		if items == nil {
			return "[]json.RawMessage", nullable
		}
		elem, elemNull := g.typeOf(items, hint+"Item")
		if elemNull {
			elem = pointer(elem)
		}
		return "[]" + elem, nullable
	case "object":
		if props, _ := s["properties"].(schema); len(props) > 0 {
			name := g.inlineName(s, hint)
			g.declareNamed(name, s)
			return name, nullable
		}
		if extra, ok := s["additionalProperties"].(schema); ok {
			elem, elemNull := g.typeOf(extra, hint+"Value")
			if elemNull {
				elem = pointer(elem)
			}
			return "map[string]" + elem, nullable
		}
		return "map[string]any", nullable
	}
	return "json.RawMessage", nullable
}

// inlineName names an inline schema: its title if it has one, else hint.
func (g *generator) inlineName(s schema, hint string) string {
	return g.freeName(s, str(s["title"]), hint, fmt.Sprintf("inline:%p", s))
}

// freeName is the first of the title, the hint, or the hint with a number,
// that no definition has and nothing else has claimed. Schemas name their
// inline shapes freely, so these collide, and the result must not.
func (g *generator) freeName(s schema, title, hint, owner string) string {
	var candidates []string
	if title != "" {
		candidates = append(candidates, ident(title))
	}
	candidates = append(candidates, hint)
	for i := 2; i < 10; i++ {
		candidates = append(candidates, fmt.Sprintf("%s%d", hint, i))
	}
	for _, name := range candidates {
		if g.isDefinition(name) {
			continue
		}
		if g.claim(name, owner) == nil {
			return name
		}
	}
	g.fail("no free Go name for %s", hint)
	return hint
}

// isDefinition says whether a definition of this name exists, v1 or v2: an
// inline schema titled the same must not take its name.
func (g *generator) isDefinition(title string) bool {
	if _, err := g.resolve("#/definitions/" + title); err == nil {
		return true
	}
	_, err := g.resolve("#/definitions/v2/" + title)
	return err == nil
}

func (g *generator) structDecl(name string, s schema) string {
	props, _ := s["properties"].(schema)
	required := map[string]bool{}
	for _, r := range anySlice(s["required"]) {
		required[str(r)] = true
	}
	var b strings.Builder
	fmt.Fprintf(&b, "type %s struct {\n", name)
	seen := map[string]bool{}
	for _, prop := range sortedKeys(props) {
		ps, _ := props[prop].(schema)
		field := ident(prop)
		if seen[field] {
			g.fail("%s: two properties map to field %s", name, field)
		}
		seen[field] = true
		typ, nullable := g.typeOf(ps, name+field)
		tag := prop
		switch {
		case !required[prop]:
			typ = pointer(typ)
			tag += ",omitempty"
		case nullable:
			typ = pointer(typ)
		}
		b.WriteString(comment(str(ps["description"])))
		fmt.Fprintf(&b, "\t%s %s `json:%q`\n", field, typ, tag)
	}
	b.WriteString("}\n")
	return b.String()
}

// variant is one arm of a union.
type variant struct {
	field  string // the union's field for it
	typ    string // its Go type
	tag    string // its discriminator value, or its one key
	schema schema
}

// union declares a oneOf. Plain string arms fold into Value; object arms are
// told apart by a discriminator property every one of them pins to a single
// value (`type`, `method`, ...) or, failing that, by their one key.
func (g *generator) union(name string, s schema) string {
	arms := anySlice(s["oneOf"])
	if arms == nil {
		arms = anySlice(s["anyOf"])
	}
	var objects []schema
	hasString := false
	for _, a := range arms {
		as, _ := a.(schema)
		types, _ := typesOf(as)
		switch {
		case len(types) == 1 && types[0] == "string":
			hasString = true
		case len(types) == 1 && types[0] == "object" || as["properties"] != nil:
			objects = append(objects, as)
		default:
			return fmt.Sprintf("type %s = json.RawMessage\n", name)
		}
	}
	if len(objects) == 0 {
		// Only strings: an open enum.
		return enumDecl(name, enumValues(s))
	}
	disc := discriminator(objects)
	var variants []variant
	for _, o := range objects {
		var tag string
		if disc != "" {
			tag = singleValue(o["properties"].(schema)[disc].(schema))
		} else {
			keys := sortedKeys(asSchema(o["properties"]))
			if len(keys) != 1 {
				return fmt.Sprintf("type %s = json.RawMessage\n", name)
			}
			tag = keys[0]
		}
		field := ident(tag)
		typeName := g.freeName(o, str(o["title"]), name+field, fmt.Sprintf("variant:%p", o))
		for _, v := range variants {
			if v.field == field {
				g.fail("%s: two variants map to field %s", name, field)
			}
		}
		g.declareNamed(typeName, o)
		variants = append(variants, variant{field: field, typ: typeName, tag: tag, schema: o})
	}

	var b strings.Builder
	fmt.Fprintf(&b, "type %s struct {\n", name)
	if disc != "" {
		fmt.Fprintf(&b, "\t// %s is the %q the JSON carried, known variant or not.\n\t%s string `json:\"-\"`\n", ident(disc), disc, ident(disc))
	}
	if hasString {
		b.WriteString("\t// Value is set when the JSON was a plain string.\n\tValue string `json:\"-\"`\n")
	}
	for _, v := range variants {
		fmt.Fprintf(&b, "\t%s *%s `json:\"-\"`\n", v.field, v.typ)
	}
	b.WriteString("\t// Raw is the JSON this was decoded from; for a variant this code does not know, it is all there is.\n\tRaw json.RawMessage `json:\"-\"`\n}\n\n")

	// MarshalJSON: whichever arm is set, its discriminator filled in.
	fmt.Fprintf(&b, "func (u %s) MarshalJSON() ([]byte, error) {\n", name)
	if hasString {
		b.WriteString("\tif u.Value != \"\" {\n\t\treturn json.Marshal(u.Value)\n\t}\n")
	}
	for _, v := range variants {
		fmt.Fprintf(&b, "\tif u.%s != nil {\n", v.field)
		if disc != "" {
			fmt.Fprintf(&b, "\t\tv := *u.%s\n\t\tif v.%s == \"\" {\n\t\t\tv.%s = %q\n\t\t}\n\t\treturn json.Marshal(v)\n", v.field, ident(disc), ident(disc), v.tag)
		} else {
			fmt.Fprintf(&b, "\t\treturn json.Marshal(u.%s)\n", v.field)
		}
		b.WriteString("\t}\n")
	}
	b.WriteString("\tif len(u.Raw) > 0 {\n\t\treturn u.Raw, nil\n\t}\n\treturn []byte(\"null\"), nil\n}\n\n")

	// UnmarshalJSON: keep the raw JSON, then decode the arm it names.
	fmt.Fprintf(&b, "func (u *%s) UnmarshalJSON(data []byte) error {\n", name)
	fmt.Fprintf(&b, "\t*u = %s{Raw: append(json.RawMessage(nil), data...)}\n", name)
	if hasString {
		b.WriteString("\tif len(data) > 0 && data[0] == '\"' {\n\t\treturn json.Unmarshal(data, &u.Value)\n\t}\n")
	}
	if disc != "" {
		fmt.Fprintf(&b, "\tvar head struct {\n\t\tTag string `json:%q`\n\t}\n", disc)
		b.WriteString("\tif json.Unmarshal(data, &head) != nil {\n\t\treturn nil\n\t}\n")
		fmt.Fprintf(&b, "\tu.%s = head.Tag\n\tswitch head.Tag {\n", ident(disc))
		for _, v := range variants {
			fmt.Fprintf(&b, "\tcase %q:\n\t\tu.%s = new(%s)\n\t\treturn json.Unmarshal(data, u.%s)\n", v.tag, v.field, v.typ, v.field)
		}
		b.WriteString("\t}\n\treturn nil\n}\n")
	} else {
		b.WriteString("\tvar keys map[string]json.RawMessage\n\tif json.Unmarshal(data, &keys) != nil {\n\t\treturn nil\n\t}\n")
		for _, v := range variants {
			fmt.Fprintf(&b, "\tif _, ok := keys[%q]; ok {\n\t\tu.%s = new(%s)\n\t\treturn json.Unmarshal(data, u.%s)\n\t}\n", v.tag, v.field, v.typ, v.field)
		}
		b.WriteString("\treturn nil\n}\n")
	}
	return b.String()
}

// discriminator is the property every object arm pins to one value, if any.
func discriminator(objects []schema) string {
	candidates := []string{"type", "method", "kind"}
	if len(objects) > 0 {
		for _, k := range sortedKeys(asSchema(objects[0]["properties"])) {
			if !slices.Contains(candidates, k) {
				candidates = append(candidates, k)
			}
		}
	}
	for _, c := range candidates {
		ok := true
		values := map[string]bool{}
		for _, o := range objects {
			p, _ := asSchema(o["properties"])[c].(schema)
			v := singleValue(p)
			if p == nil || v == "" || values[v] {
				ok = false
				break
			}
			values[v] = true
		}
		if ok {
			return c
		}
	}
	return ""
}

func singleValue(s schema) string {
	if s == nil {
		return ""
	}
	if c, ok := s["const"].(string); ok {
		return c
	}
	values := anySlice(s["enum"])
	if len(values) == 1 {
		return str(values[0])
	}
	return ""
}

func enumDecl(name string, values []string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "type %s string\n\n", name)
	if len(values) == 0 {
		return b.String()
	}
	b.WriteString("const (\n")
	seen := map[string]bool{}
	for _, v := range values {
		c := name + ident(v)
		if seen[c] {
			continue
		}
		seen[c] = true
		fmt.Fprintf(&b, "\t%s %s = %q\n", c, name, v)
	}
	b.WriteString(")\n")
	return b.String()
}

func isUnion(s schema) bool {
	if arms := anySlice(s["oneOf"]); len(arms) > 0 {
		return true
	}
	return false
}

func isStringEnum(s schema) bool {
	types, _ := typesOf(s)
	return len(types) == 1 && types[0] == "string" && len(anySlice(s["enum"])) > 0
}

func isStruct(s schema) bool {
	props, _ := s["properties"].(schema)
	return len(props) > 0
}

func enumValues(s schema) []string {
	var out []string
	for _, v := range anySlice(s["enum"]) {
		if v != nil {
			out = append(out, str(v))
		}
	}
	for _, a := range anySlice(s["oneOf"]) {
		out = append(out, enumValues(asSchema(a))...)
	}
	return out
}

// typesOf is s's "type" without "null", and whether it had "null".
func typesOf(s schema) ([]string, bool) {
	var types []string
	nullable := false
	switch t := s["type"].(type) {
	case string:
		types = []string{t}
	case []any:
		for _, x := range t {
			types = append(types, str(x))
		}
	}
	if slices.Contains(types, "null") {
		nullable = true
		types = slices.DeleteFunc(types, func(t string) bool { return t == "null" })
	}
	if len(types) == 0 {
		if _, ok := s["properties"]; ok {
			types = []string{"object"}
		} else if enum := anySlice(s["enum"]); len(enum) > 0 {
			types = []string{"string"}
		}
	}
	return types, nullable
}

func withoutNull(arms []any) ([]schema, bool) {
	var rest []schema
	nullable := false
	for _, a := range arms {
		as := asSchema(a)
		if t, _ := as["type"].(string); t == "null" {
			nullable = true
			continue
		}
		rest = append(rest, as)
	}
	return rest, nullable
}

func pointer(typ string) string {
	if strings.HasPrefix(typ, "[]") || strings.HasPrefix(typ, "map[") || typ == "json.RawMessage" || typ == "any" || strings.HasPrefix(typ, "*") {
		return typ
	}
	return "*" + typ
}

// ident makes an exported Go identifier of a JSON name: "on-request" is
// OnRequest, "item/started" ItemStarted, "execpolicy_amendment"
// ExecpolicyAmendment.
func ident(name string) string {
	var b strings.Builder
	upper := true
	for _, r := range name {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upper = true
			continue
		}
		if upper {
			b.WriteRune(unicode.ToUpper(r))
			upper = false
		} else {
			b.WriteRune(r)
		}
	}
	out := b.String()
	if out == "" {
		return "X"
	}
	if unicode.IsDigit(rune(out[0])) {
		out = "N" + out
	}
	return out
}

func comment(text string) string {
	text = strings.TrimSpace(text)
	if text == "" {
		return ""
	}
	var b strings.Builder
	for _, line := range strings.Split(text, "\n") {
		b.WriteString("// " + strings.TrimRight(line, " \t") + "\n")
	}
	return b.String()
}

func str(v any) string {
	s, _ := v.(string)
	return s
}

func anySlice(v any) []any {
	s, _ := v.([]any)
	return s
}

func asSchema(v any) schema {
	s, _ := v.(schema)
	return s
}

func toAny(s []schema) []any {
	out := make([]any, len(s))
	for i, x := range s {
		out[i] = x
	}
	return out
}

func sortedKeys(m schema) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func equalJSON(a, b any) bool {
	x, _ := json.Marshal(a)
	y, _ := json.Marshal(b)
	return bytes.Equal(x, y)
}
